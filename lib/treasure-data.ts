export const markerIdFor = (
  locationId: LocationId,
  stage: MarkerStage
) => {
  if (stage === 3) {
    return `treasure-${locationId}`;
  }

  return `hint-${locationId}-${stage}`;
};


// --------------------------------------------------
// 보물 3개 무작위 배정
// --------------------------------------------------

export const assignTreasures = (
  currentLocation: LocationId
): LocationId[] => {
  return treasureMarkerLocationIds
    .filter((id) => id !== currentLocation)
    .sort(() => Math.random() - 0.5)
    .slice(0, 3);
};
