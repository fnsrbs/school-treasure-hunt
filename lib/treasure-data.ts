export const findLocation = (id: LocationId): Location => {
  const existingLocation = locations.find(
    (location) => location.id === id
  );

  if (existingLocation) {
    return {
      ...existingLocation,

      // locations에 직접 입력된 힌트보다
      // locationHintText에 있는 힌트를 우선 사용
      hints:
        locationHintText[id] ??
        existingLocation.hints,
    };
  }

  const defaultHints: [string, string, string] = [
    `${firstHintAreas[id] ?? '학교 지도에 표시된 구역'} 쪽으로 이동해 보세요.`,
    '주변의 복도와 안내 표지를 천천히 살펴보세요.',
    '주변에 설치된 AR 마커를 자세히 찾아보세요.',
  ];

  return {
    id,
    name: locationNames[id] ?? id,
    floor: 1,
    markerId: '',
    mapPosition: '',
    hints:
      locationHintText[id] ??
      defaultHints,
  };
};


